def encrypt(data, crypto_context, keys, order="ROW_MAJOR"):
    """
    Here data is encrypted using the crypto_context and the keys.
    We are using 'tile' packing here
    """

    if order == "ROW_MAJOR":
        order = onp.ROW_MAJOR
    else:
        order = onp.COL_MAJOR

    batch_size = crypto_context.GetRingDimension() // 2

    enc_data = onp.array(
        cc=crypto_context,
        data=data,
        batch_size=batch_size,
        order=order,
        mode="tile",
        fhe_type="C",
        public_key=keys.publicKey
    )

    return enc_data

def check(encrypted, clear, keys):
    print("Checking now....")
    for e, c in zip(encrypted, clear):
        dec = e.decrypt(keys.secretKey, unpack_type="original")
        print(np.abs(dec-c).sum())



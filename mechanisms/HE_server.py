    def _compute_oneway(self, enc_data, attr):
        """
        Compute one-way marginal for a single attribute.
        Sum across columns corresponding to that attribute.
        """
        start_col, end_col = self.attr_column_ranges[attr]
        # Sum across columns: ω(N-1) additions
        marginal = np.sum(enc_data[:, start_col:end_col], axis=0)
        return marginal
    
    def _compute_oneway_he(self, enc_data, attr):
        """
        HE-emulation of one-way marginal.

        Model:
        - Each row of enc_data is conceptually an encrypted ciphertext
            with d packed slots.
        - We accumulate rows using a loop (ciphertext additions).
        - We rotate once to bring the attribute block to the front.

        Contract:
        - Let width = end_col - start_col.
        - The first `width` slots of the returned vector contain:
                np.sum(enc_data[:, start_col:end_col], axis=0)
        - All remaining slots are undefined and must be ignored.

        No masking is performed.
        """
        start_col, end_col = self.attr_column_ranges[attr]
        length = end_col - start_col

        # select start_col to end_col from self.oneway vector
        marginal = slice_vector_he(self.oneway, start_col, end_col, self.keys)

        return marginal
    
    def _compute_twoway(self, enc_data, attr1, attr2):
        """
        Compute two-way marginal for two attributes.
        Element-wise multiply columns and sum.
        """
        start1, end1 = self.attr_column_ranges[attr1]
        start2, end2 = self.attr_column_ranges[attr2]
        # Get columns for each attribute
        cols1 = select_columns(enc_data, start1, end1)  # shape: (N, ω1)
        cols2 = select_columns(enc_data, start2, end2)  # shape: (N, ω2)

        marginal = cols1.T @ cols2

        return marginal.flatten()
    
    def _compute_twoway_he(self, enc_mat, attr1, attr2):
        """
        Need select_column
        """
        start1, end1 = self.attr_column_ranges[attr1]
        start2, end2 = self.attr_column_ranges[attr2]

        dot_prod = []
        print("Gathering the dot products...")
        for i in range(start1, end1):
            col1 = select_column_he(enc_mat, i, self.crypto_context, self.keys)
            for j in range(start2, end2):
                col2 = select_column_he(enc_mat, j, self.crypto_context, self.keys)
                dot_prod.append(dot_product(col1, col2, self.keys))

        marginal = np.zeros(len(dot_prod))
        marginal_enc_cum = onp.array(
                cc=self.crypto_context,
                data=marginal,
                batch_size=self.enc_data.batch_size,
                order=onp.ROW_MAJOR,
                mode="tile",
                fhe_type="C",
                public_key=self.keys.publicKey,
            )

        marginal_transformed_enc = transform_marginal(dot_prod)
        print("Arranging the dot_products...")
        for i in range(len(marginal_transformed_enc)):
            selection_vector = np.zeros(len(marginal_transformed_enc))
            selection_vector[i] = 1.0
            # encrypt it
            selection_vector_enc = onp.array(
                cc=self.crypto_context,
                data=selection_vector,
                batch_size=self.enc_data.batch_size,
                order=onp.ROW_MAJOR,
                mode="tile",
                fhe_type="C",
                public_key=self.keys.publicKey,
            )
            
            marginal_enc_cum += selection_vector_enc * marginal_transformed_enc[i]
        print("Done with the dot products!!")
        return marginal_enc_cum


    def _compute_kway(self, enc_data, clique):
        """
        Compute k-way marginal for k attributes.
        """
        # Get columns for each attribute in the clique
        columns = []
        shapes = []
        for attr in clique:
            start, end = self.attr_column_ranges[attr]
            columns.append(enc_data[:, start:end])
            shapes.append(end - start)

        # Create k-dimensional marginal
        marginal = np.zeros(shapes)

        # Generate all combinations of bin indices
        from itertools import product
        for indices in product(*[range(s) for s in shapes]):
            # Element-wise multiply across all attributes
            result = np.ones(enc_data.shape[0])
            for col_idx, bin_idx in enumerate(indices):
                result *= columns[col_idx][:, bin_idx]
            marginal[indices] = np.sum(result)

        return marginal.flatten()


